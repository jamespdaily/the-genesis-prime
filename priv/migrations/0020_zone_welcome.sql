-- Content table `zone_welcome`: the Tutorial row each WorldZone shows when a player lands
-- in it or walks into it from a zone with another welcome, one row each, loaded once at
-- start into a persistent term (genesis_prime/content) and never queried during play.
-- It follows the pattern of `server_proxy` (0018): `source`, `source_row` and `reason`,
-- and the same checks.
--
-- A row says "WorldZone `world_zone_id` shows Tutorial `tutorial_id`": the client's tables
-- link no zone to a Tutorial row, so the link is the server's choice. A Tutorial row of
-- category 29 whose first page title is "Welcome to X" belongs to each WorldZone named X
-- (the exact name, case ignored, a leading "the " dropped); a zone with no row of its own
-- takes the row of its nearest parent that has one (genesis_prime/game/zone_welcome).

create table zone_welcome (
  world_zone_id integer not null,
  tutorial_id integer not null,
  source text not null,
  source_row integer,
  reason text,
  constraint zone_welcome_pkey primary key (world_zone_id),
  constraint zone_welcome_source_is_a_content_source
    foreign key (source) references content_source (name),
  constraint zone_welcome_ids_are_positive
    check (world_zone_id > 0 and tutorial_id > 0),
  constraint zone_welcome_source_row_is_unique unique (source, source_row),
  constraint zone_welcome_source_row_is_positive check (source_row > 0),
  constraint zone_welcome_world_database_row_has_a_source_row
    check ((source = 'world_database') = (source_row is not null)),
  constraint zone_welcome_other_source_states_its_reason
    check (source = 'world_database' or reason is not null),
  constraint zone_welcome_reason_says_something
    check (reason is null or length(trim(reason)) > 0)
);

